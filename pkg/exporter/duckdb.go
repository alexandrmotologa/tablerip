package exporter

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/alexandrmotologa/tablerip/pkg/grid"
)

// DuckDBExporter generates DuckDB SQL scripts and ingestion manifests.
type DuckDBExporter struct{}

// NewDuckDBExporter creates a DuckDBExporter.
func NewDuckDBExporter() *DuckDBExporter {
	return &DuckDBExporter{}
}

// GenerateSQLScript creates a standalone SQL script that sets up DuckDB tables from extracted data or Parquet files.
func (de *DuckDBExporter) GenerateSQLScript(table *grid.Table, parquetPath string, outputPath string) error {
	if table == nil {
		return fmt.Errorf("table is nil")
	}

	if err := os.MkdirAll(filepath.Dir(outputPath), 0755); err != nil {
		return fmt.Errorf("failed to create directory: %w", err)
	}

	tableName := sanitizeIdentifier("duck_" + table.ID)
	var sb strings.Builder

	sb.WriteString(fmt.Sprintf("-- DuckDB Ingestion Script for Table: %s\n", table.Title))
	sb.WriteString("-- Auto-generated by tablerip pure Go engine\n\n")

	// View/Table directly from Parquet
	if parquetPath != "" {
		absParquet, _ := filepath.Abs(parquetPath)
		absParquet = filepath.ToSlash(absParquet)
		sb.WriteString(fmt.Sprintf("-- Direct zero-copy Parquet query\n"))
		sb.WriteString(fmt.Sprintf("CREATE OR REPLACE VIEW %s_raw AS \n", tableName))
		sb.WriteString(fmt.Sprintf("SELECT * FROM read_parquet('%s');\n\n", absParquet))
	}

	// Structured DDL
	var colDefs []string
	colDefs = append(colDefs, "row_id BIGINT PRIMARY KEY")
	colDefs = append(colDefs, "hierarchy_level INTEGER")
	colDefs = append(colDefs, "row_label VARCHAR")
	colDefs = append(colDefs, "section VARCHAR")
	colDefs = append(colDefs, "is_total BOOLEAN")

	var valCols []string
	for colIdx := 1; colIdx < len(table.Columns); colIdx++ {
		cName := sanitizeIdentifier("col_" + table.Columns[colIdx].Name)
		colDefs = append(colDefs, fmt.Sprintf("%s DOUBLE", cName))
		valCols = append(valCols, cName)
	}

	sb.WriteString(fmt.Sprintf("CREATE TABLE IF NOT EXISTS %s (\n  %s\n);\n\n",
		tableName, strings.Join(colDefs, ",\n  ")))

	// Insert statements
	for _, row := range table.DataRows() {
		var values []string
		values = append(values, fmt.Sprintf("%d", row.Index))
		values = append(values, fmt.Sprintf("%d", row.Level))
		values = append(values, fmt.Sprintf("'%s'", strings.ReplaceAll(row.Label, "'", "''")))
		if row.Section != "" {
			values = append(values, fmt.Sprintf("'%s'", strings.ReplaceAll(row.Section, "'", "''")))
		} else {
			values = append(values, "NULL")
		}
		values = append(values, fmt.Sprintf("%t", row.IsTotal))

		for colIdx := 1; colIdx < len(table.Columns); colIdx++ {
			cell := row.GetCell(colIdx)
			if cell != nil && cell.IsNumeric {
				values = append(values, fmt.Sprintf("%.4f", cell.Value))
			} else {
				values = append(values, "NULL")
			}
		}

		sb.WriteString(fmt.Sprintf("INSERT INTO %s VALUES (%s);\n", tableName, strings.Join(values, ", ")))
	}

	return os.WriteFile(outputPath, []byte(sb.String()), 0644)
}
